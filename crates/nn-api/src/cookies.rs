//! Cookie names, parsing, and `Set-Cookie` construction.
//!
//! Session tokens are 256-bit random values looked up by hash server-side,
//! so the cookie needs no signature: a forged value simply doesn't match.

use std::time::Duration;

use http::{HeaderMap, HeaderValue};

/// HttpOnly cookie carrying the session token.
pub const SESSION_COOKIE: &str = "nn_session";
/// JS-readable cookie carrying the CSRF token for double-submit checks.
pub const CSRF_COOKIE: &str = "nn_csrf";
/// Header that must echo the CSRF cookie on mutating requests.
pub const CSRF_HEADER: &str = "x-csrf-token";

/// Returns the value of cookie `name` from the request's `Cookie` headers.
pub fn get(headers: &HeaderMap, name: &str) -> Option<String> {
    headers
        .get_all(http::header::COOKIE)
        .iter()
        .filter_map(|v| v.to_str().ok())
        .flat_map(|v| v.split(';'))
        .filter_map(|pair| pair.trim().split_once('='))
        .find(|(k, _)| *k == name)
        .map(|(_, v)| v.trim_matches('"').to_owned())
        .filter(|v| !v.is_empty())
}

/// `Set-Cookie` for a new or renewed session.
pub fn session(token: &str, max_age: Duration, secure: bool) -> HeaderValue {
    build(SESSION_COOKIE, token, Some(max_age), true, "Lax", secure)
}

/// `Set-Cookie` that deletes the session cookie.
pub fn clear_session(secure: bool) -> HeaderValue {
    build(
        SESSION_COOKIE,
        "",
        Some(Duration::ZERO),
        true,
        "Lax",
        secure,
    )
}

/// `Set-Cookie` for the CSRF token. Readable by scripts so the UI can echo
/// it; `SameSite=Strict` keeps it off cross-site requests entirely.
pub fn csrf(token: &str, secure: bool) -> HeaderValue {
    build(CSRF_COOKIE, token, None, false, "Strict", secure)
}

fn build(
    name: &str,
    value: &str,
    max_age: Option<Duration>,
    http_only: bool,
    same_site: &str,
    secure: bool,
) -> HeaderValue {
    let mut cookie = format!("{name}={value}; Path=/; SameSite={same_site}");
    if let Some(max_age) = max_age {
        cookie.push_str(&format!("; Max-Age={}", max_age.as_secs()));
    }
    if http_only {
        cookie.push_str("; HttpOnly");
    }
    if secure {
        cookie.push_str("; Secure");
    }
    // Values are base64url tokens generated by us, so this cannot fail.
    HeaderValue::from_str(&cookie).expect("cookie is valid header value")
}

/// Whether a response already sets cookie `name`.
pub fn response_sets(headers: &HeaderMap, name: &str) -> bool {
    headers
        .get_all(http::header::SET_COOKIE)
        .iter()
        .filter_map(|v| v.to_str().ok())
        .any(|v| v.split_once('=').is_some_and(|(k, _)| k == name))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_cookie_headers() {
        let mut headers = HeaderMap::new();
        headers.append(http::header::COOKIE, "a=1; nn_session=tok".parse().unwrap());
        headers.append(http::header::COOKIE, "nn_csrf=\"c\"".parse().unwrap());
        assert_eq!(get(&headers, "nn_session").as_deref(), Some("tok"));
        assert_eq!(get(&headers, "nn_csrf").as_deref(), Some("c"));
        assert_eq!(get(&headers, "missing"), None);
    }

    #[test]
    fn session_cookie_attributes() {
        let v = session("tok", Duration::from_secs(60), true);
        assert_eq!(
            v,
            "nn_session=tok; Path=/; SameSite=Lax; Max-Age=60; HttpOnly; Secure"
        );
        let v = csrf("c", false);
        assert_eq!(v, "nn_csrf=c; Path=/; SameSite=Strict");
        assert!(clear_session(false).to_str().unwrap().contains("Max-Age=0"));
    }

    #[test]
    fn detects_cookie_in_response() {
        let mut headers = HeaderMap::new();
        headers.append(http::header::SET_COOKIE, csrf("x", false));
        assert!(response_sets(&headers, CSRF_COOKIE));
        assert!(!response_sets(&headers, SESSION_COOKIE));
    }
}
