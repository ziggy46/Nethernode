//! Partial uploads on disk: one preallocated file per upload, written in
//! place at the client's offset.

use std::io::{self, Read, SeekFrom};
use std::path::{Path, PathBuf};

use bytes::Bytes;
use futures_util::{Stream, StreamExt};
use sha2::{Digest, Sha256};
use tokio::io::{AsyncSeekExt, AsyncWriteExt};

/// Bytes gathered from the request body before each write.
const WRITE_BUFFER: usize = 1024 * 1024;

/// The folder holding partial uploads (`<data>/tmp/uploads`).
#[derive(Debug, Clone)]
pub struct TempStore {
    dir: PathBuf,
}

impl TempStore {
    /// Opens (creating if needed) the folder for partial uploads.
    pub fn open(dir: impl Into<PathBuf>) -> io::Result<Self> {
        let dir = dir.into();
        std::fs::create_dir_all(&dir)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            std::fs::set_permissions(&dir, std::fs::Permissions::from_mode(0o700))?;
        }
        Ok(Self { dir })
    }

    /// The folder itself.
    pub fn dir(&self) -> &Path {
        &self.dir
    }

    /// Where upload `id` is stored. IDs are generated by NetherNode
    /// (alphanumeric), never taken from a client as a path.
    pub fn path(&self, id: &str) -> io::Result<PathBuf> {
        if id.is_empty() || !id.bytes().all(|b| b.is_ascii_alphanumeric()) {
            return Err(io::Error::new(io::ErrorKind::InvalidInput, "bad upload id"));
        }
        Ok(self.dir.join(id))
    }

    /// Creates the file for a new upload of `len` bytes, reserving the disk
    /// space up front where the filesystem allows, so a full disk fails now
    /// rather than hours into the upload.
    pub fn create(&self, id: &str, len: u64) -> io::Result<()> {
        let path = self.path(id)?;
        let mut options = std::fs::OpenOptions::new();
        options.write(true).create_new(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.mode(0o600);
        }
        let file = options.open(&path)?;
        if let Err(e) = preallocate(&file, len) {
            drop(file);
            let _ = std::fs::remove_file(&path);
            return Err(e);
        }
        Ok(())
    }

    /// Deletes upload `id`'s file, if it exists.
    pub fn remove(&self, id: &str) -> io::Result<()> {
        match std::fs::remove_file(self.path(id)?) {
            Err(e) if e.kind() != io::ErrorKind::NotFound => Err(e),
            _ => Ok(()),
        }
    }

    /// IDs of every partial upload on disk.
    pub fn ids(&self) -> io::Result<Vec<String>> {
        let mut ids = Vec::new();
        for entry in std::fs::read_dir(&self.dir)? {
            let entry = entry?;
            if let Some(name) = entry.file_name().to_str()
                && self.path(name).is_ok()
            {
                ids.push(name.to_owned());
            }
        }
        Ok(ids)
    }

    /// Free space for uploads, where the platform reports it.
    pub fn available_space(&self) -> Option<u64> {
        available_space(&self.dir)
    }
}

#[cfg(target_os = "linux")]
fn preallocate(file: &std::fs::File, len: u64) -> io::Result<()> {
    if len == 0 {
        return Ok(());
    }
    match rustix::fs::fallocate(file, rustix::fs::FallocateFlags::empty(), 0, len) {
        Ok(()) => Ok(()),
        // Filesystems without fallocate: fall back to a sparse file.
        Err(rustix::io::Errno::OPNOTSUPP | rustix::io::Errno::NOSYS) => file.set_len(len),
        Err(e) => Err(e.into()),
    }
}

#[cfg(not(target_os = "linux"))]
fn preallocate(file: &std::fs::File, len: u64) -> io::Result<()> {
    file.set_len(len)
}

#[cfg(target_os = "linux")]
fn available_space(dir: &Path) -> Option<u64> {
    let stat = rustix::fs::statvfs(dir).ok()?;
    Some(stat.f_bavail.saturating_mul(stat.f_frsize))
}

#[cfg(not(target_os = "linux"))]
fn available_space(_dir: &Path) -> Option<u64> {
    None
}

/// The result of one `PATCH`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Chunk {
    /// Bytes written and synced to disk, starting at the request's offset.
    pub written: u64,
    /// The connection dropped before the body ended. What arrived is kept
    /// (unless a checksum was given), so the client resumes from there.
    pub interrupted: bool,
}

/// Why a chunk wasn't stored.
#[derive(Debug, thiserror::Error)]
pub enum ChunkError {
    /// The body is longer than allowed (per request, or past the end of the
    /// upload). Nothing is kept.
    #[error("the request body is too large")]
    TooLarge,
    /// The body didn't match its `Upload-Checksum`. Nothing is kept.
    #[error("the chunk doesn't match its checksum")]
    ChecksumMismatch,
    /// The connection dropped and the chunk had a checksum, so the part that
    /// arrived can't be verified. Nothing is kept.
    #[error("the connection dropped before the chunk could be verified")]
    Interrupted,
    /// Writing failed.
    #[error(transparent)]
    Io(#[from] io::Error),
}

/// Streams a request body into `path` at `offset`, accepting at most `max`
/// bytes. Data is synced to disk before returning, so the caller can record
/// the new offset.
pub async fn write_chunk<S, E>(
    path: &Path,
    offset: u64,
    max: u64,
    mut body: S,
    checksum: Option<[u8; 32]>,
) -> Result<Chunk, ChunkError>
where
    S: Stream<Item = Result<Bytes, E>> + Unpin,
{
    let mut file = tokio::fs::OpenOptions::new().write(true).open(path).await?;
    file.seek(SeekFrom::Start(offset)).await?;
    let mut hasher = checksum.map(|_| Sha256::new());
    let mut buffer: Vec<u8> = Vec::with_capacity(WRITE_BUFFER);
    let mut written: u64 = 0;
    let mut interrupted = false;

    loop {
        match body.next().await {
            Some(Ok(data)) => {
                if written + (buffer.len() + data.len()) as u64 > max {
                    return Err(ChunkError::TooLarge);
                }
                if let Some(h) = hasher.as_mut() {
                    h.update(&data);
                }
                buffer.extend_from_slice(&data);
                if buffer.len() >= WRITE_BUFFER {
                    file.write_all(&buffer).await?;
                    written += buffer.len() as u64;
                    buffer.clear();
                }
            }
            Some(Err(_)) => {
                interrupted = true;
                break;
            }
            None => break,
        }
    }

    if let (Some(want), Some(h)) = (checksum, hasher) {
        if interrupted {
            return Err(ChunkError::Interrupted);
        }
        if h.finalize().as_slice() != want {
            return Err(ChunkError::ChecksumMismatch);
        }
    }
    file.write_all(&buffer).await?;
    written += buffer.len() as u64;
    file.flush().await?;
    file.sync_data().await?;
    Ok(Chunk {
        written,
        interrupted,
    })
}

/// SHA-256 of the first `len` bytes of `path`. Blocking.
pub fn sha256_file(path: &Path, len: u64) -> io::Result<[u8; 32]> {
    let mut file = std::fs::File::open(path)?.take(len);
    let mut hasher = Sha256::new();
    let mut buffer = vec![0u8; WRITE_BUFFER];
    loop {
        let n = file.read(&mut buffer)?;
        if n == 0 {
            break;
        }
        hasher.update(&buffer[..n]);
    }
    Ok(hasher.finalize().into())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn body(
        parts: Vec<Result<&'static [u8], ()>>,
    ) -> impl Stream<Item = Result<Bytes, ()>> + Unpin {
        futures_util::stream::iter(parts.into_iter().map(|p| p.map(Bytes::from_static)))
    }

    fn sha(data: &[u8]) -> [u8; 32] {
        Sha256::digest(data).into()
    }

    #[tokio::test]
    async fn chunks_land_at_their_offset() {
        let dir = tempfile::tempdir().unwrap();
        let store = TempStore::open(dir.path().join("uploads")).unwrap();
        store.create("A1", 10).unwrap();
        let path = store.path("A1").unwrap();
        assert_eq!(std::fs::metadata(&path).unwrap().len(), 10);

        let first = write_chunk(&path, 0, 10, body(vec![Ok(b"hello")]), None)
            .await
            .unwrap();
        assert_eq!(
            first,
            Chunk {
                written: 5,
                interrupted: false
            }
        );
        let second = write_chunk(
            &path,
            5,
            5,
            body(vec![Ok(b"wor"), Ok(b"ld")]),
            Some(sha(b"world")),
        )
        .await
        .unwrap();
        assert_eq!(second.written, 5);
        assert_eq!(std::fs::read(&path).unwrap(), b"helloworld");
        assert_eq!(sha256_file(&path, 10).unwrap(), sha(b"helloworld"));
    }

    #[tokio::test]
    async fn interrupted_bodies_keep_what_arrived_unless_checksummed() {
        let dir = tempfile::tempdir().unwrap();
        let store = TempStore::open(dir.path()).unwrap();
        store.create("B", 10).unwrap();
        let path = store.path("B").unwrap();
        let partial = write_chunk(&path, 0, 10, body(vec![Ok(b"abc"), Err(())]), None)
            .await
            .unwrap();
        assert_eq!(
            partial,
            Chunk {
                written: 3,
                interrupted: true
            }
        );
        assert!(matches!(
            write_chunk(
                &path,
                3,
                7,
                body(vec![Ok(b"def"), Err(())]),
                Some(sha(b"defghij"))
            )
            .await,
            Err(ChunkError::Interrupted)
        ));
    }

    #[tokio::test]
    async fn oversized_and_mismatched_chunks_are_refused() {
        let dir = tempfile::tempdir().unwrap();
        let store = TempStore::open(dir.path()).unwrap();
        store.create("C", 4).unwrap();
        let path = store.path("C").unwrap();
        assert!(matches!(
            write_chunk(&path, 0, 4, body(vec![Ok(b"toolong")]), None).await,
            Err(ChunkError::TooLarge)
        ));
        assert!(matches!(
            write_chunk(&path, 0, 4, body(vec![Ok(b"abcd")]), Some(sha(b"wxyz"))).await,
            Err(ChunkError::ChecksumMismatch)
        ));
    }

    #[test]
    fn ids_are_never_paths() {
        let dir = tempfile::tempdir().unwrap();
        let store = TempStore::open(dir.path()).unwrap();
        assert!(store.path("../etc").is_err());
        assert!(store.path("a/b").is_err());
        assert!(store.path("").is_err());
        store.create("D", 0).unwrap();
        std::fs::write(dir.path().join(".hidden"), b"").unwrap();
        assert_eq!(store.ids().unwrap(), vec!["D".to_owned()]);
        store.remove("D").unwrap();
        store.remove("D").unwrap();
    }
}
